-- Upsert(onConflict:'key') requires a unique index. Preserve existing rows; stop with a clear error if duplicate keys exist.
do $$
begin
  if exists (
    select key from public.store_settings
    where key is not null
    group by key having count(*) > 1
  ) then
    raise exception 'store_settings has duplicate non-null keys. No rows were deleted; remove/merge duplicate keys before rerunning this repair.';
  end if;
  create unique index if not exists store_settings_key_repair_uidx
    on public.store_settings(key);
end $$;

-- Older tables may have an id column but no identity/sequence default.
-- Use a standard PL/pgSQL block with a record loop.
do $repair_sequences$
declare
  tbl_name text;
  col_type text;
  seq_name text;
  current_max bigint;
begin
  foreach tbl_name in array array['products','abc_products','product_media','abc_product_media']
  loop
    select data_type
      into col_type
    from information_schema.columns
    where table_schema = 'public'
      and table_name = tbl_name
      and column_name = 'id';

    if col_type in ('bigint','integer','smallint') then
      seq_name := pg_get_serial_sequence(format('public.%I', tbl_name), 'id');

      if seq_name is null then
        execute format('create sequence if not exists public.%I', tbl_name || '_repair_id_seq');

        execute format('select coalesce(max(id), 0) from public.%I', tbl_name)
          into current_max;

        if current_max > 0 then
          execute format('select setval(%L::regclass, %s, true)',
            'public.' || tbl_name || '_repair_id_seq', current_max);
        else
          execute format('select setval(%L::regclass, 1, false)',
            'public.' || tbl_name || '_repair_id_seq');
        end if;

        execute format(
          'alter table public.%I alter column id set default nextval(%L::regclass)',
          tbl_name,
          'public.' || tbl_name || '_repair_id_seq'
        );

        execute format(
          'alter sequence public.%I owned by public.%I.id',
          tbl_name || '_repair_id_seq',
          tbl_name
        );
      end if;
    end if;
  end loop;
end
$repair_sequences$;

