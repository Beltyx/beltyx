-- Keep new BELTYX-owned product IDs in a separate range from legacy public.products IDs.
-- This is safe to re-run and also repairs an older identity sequence on an existing table.
do $$ declare seq_name text; max_id bigint; begin
  seq_name := pg_get_serial_sequence('public.abc_products','id');
  if seq_name is not null then
    select greatest(coalesce(max(id),999999),999999) into max_id from public.abc_products;
    perform setval(seq_name::regclass,max_id,true);
  end if;
end $$;

