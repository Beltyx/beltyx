-- Storage bucket used by the admin for category images, product covers, galleries and videos.
-- Remove any older policies that mention this bucket so no previous broad policy bypasses admin-only uploads.
do $$ declare p record; begin
  for p in select policyname from pg_policies
    where schemaname='storage' and tablename='objects'
      and (coalesce(qual,'') like '%product-images%' or coalesce(with_check,'') like '%product-images%')
  loop execute format('drop policy if exists %I on storage.objects',p.policyname); end loop;
end $$;
insert into storage.buckets (id,name,public,file_size_limit) values ('product-images','product-images',true,52428800)
on conflict (id) do update set public=true,file_size_limit=52428800;
drop policy if exists "Public can view BELTYX product files" on storage.objects;
